package de.schliweb.moveapiece.maia960eval;

import de.schliweb.moveapiece.maia960eval.Summary.Pairing;
import de.schliweb.moveapiece.maia960eval.Summary.Row;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Random;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Collectors;

/**
 * Compares runs of the opening study (standard chess, each run one way of sampling Maia's first
 * moves) with the baseline run and with human games:
 *
 * <ul>
 *   <li>variety: distinct lines after 8 and 12 plies in Maia-vs-Maia games, per pairing;
 *   <li>human-likeness: total variation distance of White's first move and of the opening families
 *       (lichess-org/chess-openings) to human games of the same ratings, and the share of games in
 *       the humans' ten most common families;
 *   <li>losses of the sampled moves (sampled-moves.tsv);
 *   <li>strength against Stockfish, as the shift of the performance rating per Maia level against
 *       the baseline, with a bootstrap 95 % CI over position pairs.
 * </ul>
 *
 * <pre>
 * --runs=label=dir,...   the first is the baseline
 * --human=file           from HumanMatch --openings
 * --openings=dir         chess-openings TSV files
 * --out=file
 * </pre>
 */
public final class VarianceReport {

    private static final int SUBSAMPLES = 500;
    private static final long SEED = 4242;

    private VarianceReport() {}

    public static void main(String[] args) throws Exception {
        Map<String, String> a = new HashMap<>();
        for (String arg : args) {
            a.put(arg.substring(2, arg.indexOf('=')), arg.substring(arg.indexOf('=') + 1));
        }
        Map<String, List<Row>> runs = new LinkedHashMap<>();
        Map<String, Path> dirs = new LinkedHashMap<>();
        for (String spec : a.get("runs").split(",")) {
            String[] p = spec.split("=", 2);
            dirs.put(p[0], Path.of(p[1]));
            List<Row> rows = Summary.readRows(Path.of(p[1]));
            rows.removeIf(r -> !r.ok() || !r.variant().equals("std"));
            runs.put(p[0], rows);
        }
        OpeningNames names = OpeningNames.load(Path.of(a.get("openings")));
        Map<String, List<String[]>> human = new TreeMap<>();
        for (String line : Files.readAllLines(Path.of(a.get("human")))) {
            String[] f = line.split("\t", -1);
            human.computeIfAbsent(f[0], k -> new ArrayList<>()).add(f);
        }

        StringBuilder md = new StringBuilder();
        md.append("# Maia opening variety: comparison\n\n");
        md.append("Generated by `VarianceReport`; see REPORT.md for the discussion.\n\n");
        variety(md, runs, human, names);
        families(md, runs, human, names);
        losses(md, runs, dirs);
        strength(md, runs);
        Files.writeString(Path.of(a.get("out")), md.toString());
        System.out.println("Wrote " + a.get("out"));
    }

    /** Maia-vs-Maia games of one pairing, keyed "low-high" by rating. */
    private static Map<String, List<Row>> byPairing(List<Row> rows) {
        Map<String, List<Row>> out = new TreeMap<>();
        for (Row r : rows) {
            if (r.mode().equals("mvm")) {
                String key =
                        Math.min(r.whiteElo(), r.blackElo())
                                + "-"
                                + Math.max(r.whiteElo(), r.blackElo());
                out.computeIfAbsent(key, k -> new ArrayList<>()).add(r);
            }
        }
        return out;
    }

    private static String prefix(String plies, int n) {
        String[] p = plies.isBlank() ? new String[0] : plies.split(" ");
        return String.join(" ", Arrays.copyOf(p, Math.min(n, p.length)));
    }

    private static int distinct(List<String> lines, int plies) {
        Set<String> seen = new HashSet<>();
        for (String l : lines) {
            seen.add(prefix(l, plies));
        }
        return seen.size();
    }

    /** Mean number of distinct lines in random subsets of {@code n} human games. */
    private static double humanDistinct(List<String> lines, int n, int plies) {
        Random random = new Random(SEED);
        double sum = 0;
        List<String> copy = new ArrayList<>(lines);
        for (int i = 0; i < SUBSAMPLES; i++) {
            Collections.shuffle(copy, random);
            sum += distinct(copy.subList(0, Math.min(n, copy.size())), plies);
        }
        return sum / SUBSAMPLES;
    }

    private static Map<String, Double> distribution(List<String> keys) {
        Map<String, Double> out = new HashMap<>();
        for (String k : keys) {
            out.merge(k, 1.0 / keys.size(), Double::sum);
        }
        return out;
    }

    private static double tv(Map<String, Double> p, Map<String, Double> q) {
        Set<String> all = new HashSet<>(p.keySet());
        all.addAll(q.keySet());
        double d = 0;
        for (String k : all) {
            d += Math.abs(p.getOrDefault(k, 0.0) - q.getOrDefault(k, 0.0));
        }
        return d / 2;
    }

    private static List<String> top(Map<String, Double> dist, int n) {
        return dist.entrySet().stream()
                .sorted((x, y) -> Double.compare(y.getValue(), x.getValue()))
                .limit(n)
                .map(Map.Entry::getKey)
                .collect(Collectors.toList());
    }

    private static void variety(
            StringBuilder md,
            Map<String, List<Row>> runs,
            Map<String, List<String[]>> human,
            OpeningNames names) {
        md.append("## Variety and human-likeness (Maia against Maia)\n\n");
        md.append(
                "Distinct lines among the pairing's games after 8 and 12 plies; for humans the"
                        + " mean over "
                        + SUBSAMPLES
                        + " random sets of as many games of the same ratings. TV: total"
                        + " variation distance to the humans (0 = same distribution, 1 ="
                        + " disjoint) of White's first move and of the opening family. Top 10:"
                        + " share of games in the humans' ten most common families.\n\n");
        md.append(
                "| Variant | Pairing | Games | Distinct @8 | Distinct @12 | TV first move | TV"
                        + " family | Top 10 |\n|---|---|---|---|---|---|---|---|\n");
        Set<String> pairings = new TreeSet<>();
        runs.values().forEach(rows -> pairings.addAll(byPairing(rows).keySet()));
        for (String pairing : pairings) {
            List<String[]> h = human.getOrDefault(pairing, List.of());
            List<String> hLines = h.stream().map(f -> f[3]).collect(Collectors.toList());
            Map<String, Double> hFirst =
                    distribution(hLines.stream().map(l -> prefix(l, 1)).toList());
            Map<String, Double> hFamily = distribution(hLines.stream().map(names::family).toList());
            Set<String> hTop = new HashSet<>(top(hFamily, 10));
            int n = 0;
            for (Map.Entry<String, List<Row>> run : runs.entrySet()) {
                List<Row> games = byPairing(run.getValue()).getOrDefault(pairing, List.of());
                if (games.isEmpty()) {
                    continue;
                }
                n = games.size();
                List<String> lines = games.stream().map(Row::opening).toList();
                List<String> fam = lines.stream().map(names::family).toList();
                md.append(
                        String.format(
                                Locale.ROOT,
                                "| %s | %s | %d | %d | %d | %.2f | %.2f | %.0f %% |%n",
                                run.getKey(),
                                pairing,
                                games.size(),
                                distinct(lines, 8),
                                distinct(lines, 12),
                                tv(
                                        distribution(
                                                lines.stream().map(l -> prefix(l, 1)).toList()),
                                        hFirst),
                                tv(distribution(fam), hFamily),
                                100.0 * fam.stream().filter(hTop::contains).count() / fam.size()));
            }
            if (!h.isEmpty()) {
                md.append(
                        String.format(
                                Locale.ROOT,
                                "| **humans** (%d games) | %s | %d | %.1f | %.1f | – | – | %.0f %%"
                                        + " |%n",
                                h.size(),
                                pairing,
                                n,
                                humanDistinct(hLines, n, 8),
                                humanDistinct(hLines, n, 12),
                                100.0
                                        * hLines.stream()
                                                .map(names::family)
                                                .filter(hTop::contains)
                                                .count()
                                        / hLines.size()));
            }
        }
        md.append('\n');
    }

    private static void families(
            StringBuilder md,
            Map<String, List<Row>> runs,
            Map<String, List<String[]>> human,
            OpeningNames names) {
        md.append("## Most common opening families (Maia against Maia, both pairings)\n\n");
        md.append("| Variant | Families (share of games) |\n|---|---|\n");
        List<String> hLines = new ArrayList<>();
        human.values().forEach(list -> list.forEach(f -> hLines.add(f[3])));
        md.append("| **humans** | ").append(familyList(hLines, names)).append(" |\n");
        for (Map.Entry<String, List<Row>> run : runs.entrySet()) {
            List<String> lines =
                    run.getValue().stream()
                            .filter(r -> r.mode().equals("mvm"))
                            .map(Row::opening)
                            .toList();
            if (!lines.isEmpty()) {
                md.append("| ")
                        .append(run.getKey())
                        .append(" | ")
                        .append(familyList(lines, names))
                        .append(" |\n");
            }
        }
        md.append('\n');
    }

    private static String familyList(List<String> lines, OpeningNames names) {
        Map<String, Double> dist = distribution(lines.stream().map(names::family).toList());
        return top(dist, 6).stream()
                        .map(f -> String.format(Locale.ROOT, "%s %.0f %%", f, 100 * dist.get(f)))
                        .collect(Collectors.joining(", "))
                + String.format(" (%d families)", dist.size());
    }

    private static void losses(
            StringBuilder md, Map<String, List<Row>> runs, Map<String, Path> dirs)
            throws Exception {
        md.append("## Losses of the sampled moves\n\n");
        md.append(
                "Share of sampled opening moves losing more than 100 / 200 cp by the referee,"
                        + " all games of the run.\n\n");
        Set<Integer> elos = new TreeSet<>();
        Map<String, Map<Integer, long[]>> all = new LinkedHashMap<>();
        for (String label : runs.keySet()) {
            Path file = dirs.get(label).resolve("sampled-moves.tsv");
            Map<Integer, long[]> byElo = new TreeMap<>();
            if (Files.exists(file)) {
                for (String line : Files.readAllLines(file)) {
                    String[] f = line.split("\t");
                    int elo = Integer.parseInt(f[1]);
                    int loss = Integer.parseInt(f[5]);
                    long[] t = byElo.computeIfAbsent(elo, k -> new long[3]);
                    t[0]++;
                    t[1] += loss > 100 ? 1 : 0;
                    t[2] += loss > 200 ? 1 : 0;
                    elos.add(elo);
                }
            }
            all.put(label, byElo);
        }
        md.append("| Variant | Sampled moves | > 100 cp | > 200 cp |");
        elos.forEach(e -> md.append(" > 200 cp at ").append(e).append(" |"));
        md.append("\n|---|---|---|---|");
        elos.forEach(e -> md.append("---|"));
        md.append('\n');
        for (Map.Entry<String, Map<Integer, long[]>> run : all.entrySet()) {
            long[] sum = new long[3];
            run.getValue()
                    .values()
                    .forEach(
                            t -> {
                                for (int i = 0; i < 3; i++) {
                                    sum[i] += t[i];
                                }
                            });
            if (sum[0] == 0) {
                md.append("| ").append(run.getKey()).append(" | 0 | – | – |");
                elos.forEach(e -> md.append(" – |"));
                md.append('\n');
                continue;
            }
            md.append(
                    String.format(
                            Locale.ROOT,
                            "| %s | %d | %.2f %% | %.2f %% |",
                            run.getKey(),
                            sum[0],
                            100.0 * sum[1] / sum[0],
                            100.0 * sum[2] / sum[0]));
            for (int e : elos) {
                long[] t = run.getValue().get(e);
                md.append(
                        t == null
                                ? " – |"
                                : String.format(Locale.ROOT, " %.2f %% |", 100.0 * t[2] / t[0]));
            }
            md.append('\n');
        }
        md.append('\n');
    }

    private static void strength(StringBuilder md, Map<String, List<Row>> runs) {
        md.append("## Strength against Stockfish\n\n");
        md.append(
                "Performance rating per Maia level (Stockfish's nominal scale) and its shift"
                        + " against the baseline, bootstrap 95 % CI over position pairs ("
                        + Summary.BOOTSTRAP
                        + " resamples); the mean shift averages the four levels.\n\n");
        Map.Entry<String, List<Row>> base = runs.entrySet().iterator().next();
        Set<Integer> levels = new TreeSet<>();
        base.getValue().stream()
                .filter(r -> r.mode().equals("mvs"))
                .forEach(r -> levels.add(Summary.maiaElo(r)));
        if (levels.isEmpty()) {
            md.append("No games against Stockfish in the baseline.\n\n");
            return;
        }
        md.append("| Variant |");
        levels.forEach(l -> md.append(" ").append(l).append(" |"));
        md.append(" Mean shift [95 % CI] |\n|---|");
        levels.forEach(l -> md.append("---|"));
        md.append("---|\n");
        Map<Integer, List<Pairing>> basePairings = pairings(base.getValue(), levels);
        md.append("| ").append(base.getKey()).append(" (perf.) |");
        for (int l : levels) {
            md.append(String.format(" %.0f |", Summary.performance(basePairings.get(l))));
        }
        md.append(" – |\n");
        Random random = new Random(SEED);
        for (Map.Entry<String, List<Row>> run : runs.entrySet()) {
            if (run == base || run.getValue().stream().noneMatch(r -> r.mode().equals("mvs"))) {
                continue;
            }
            Map<Integer, List<Pairing>> p = pairings(run.getValue(), levels);
            md.append("| ").append(run.getKey()).append(" |");
            double[] boots = new double[Summary.BOOTSTRAP];
            double mean = 0;
            for (int l : levels) {
                double shift =
                        Summary.performance(p.get(l)) - Summary.performance(basePairings.get(l));
                mean += shift / levels.size();
                double[] b = new double[Summary.BOOTSTRAP];
                for (int i = 0; i < Summary.BOOTSTRAP; i++) {
                    b[i] =
                            Summary.performance(Summary.resample(p.get(l), random))
                                    - Summary.performance(
                                            Summary.resample(basePairings.get(l), random));
                    boots[i] += b[i] / levels.size();
                }
                Arrays.sort(b);
                md.append(
                        String.format(
                                " %+.0f [%+.0f, %+.0f] |",
                                shift,
                                b[(int) (0.025 * Summary.BOOTSTRAP)],
                                b[(int) (0.975 * Summary.BOOTSTRAP)]));
            }
            Arrays.sort(boots);
            md.append(
                    String.format(
                            " **%+.0f** [%+.0f, %+.0f] |%n",
                            mean,
                            boots[(int) (0.025 * Summary.BOOTSTRAP)],
                            boots[(int) (0.975 * Summary.BOOTSTRAP)]));
        }
        md.append('\n');
    }

    private static Map<Integer, List<Pairing>> pairings(List<Row> rows, Set<Integer> levels) {
        Map<Integer, List<Pairing>> out = new TreeMap<>();
        for (int level : levels) {
            Map<Integer, List<Row>> bySf = new TreeMap<>();
            for (Row r : rows) {
                if (r.mode().equals("mvs") && Summary.maiaElo(r) == level) {
                    bySf.computeIfAbsent(Summary.sfElo(r), k -> new ArrayList<>()).add(r);
                }
            }
            List<Pairing> list = new ArrayList<>();
            bySf.forEach((sf, games) -> list.add(Summary.pairing(games, true, level, sf)));
            out.put(level, list);
        }
        return out;
    }
}
